    // ── Recommendation engine ─────────────────────────────────────────────────

    fun recommend(
        device:        DeviceState,
        wantSignal:    Boolean = false,
        wantFree:      Boolean = false,
        wantUntethered:Boolean = false,
    ): RecommendationResult {
        val candidates = ArrayList<BypassFeature>()
        for (candidate in bypassOptions(device.chipRange)) {
            if (candidate.requiresJailbreak && !device.isJailbroken) continue
            if (candidate.requiresImei && !device.canUseSignal) continue
            candidates.add(candidate)
        }

        val best: BypassFeature? = when {
            wantSignal && wantFree -> {
                cheapestCandidate(candidates, requireSignal = true, requireFree = true)
                    ?: cheapestCandidate(candidates, requireSignal = true)
                    ?: cheapestCandidate(candidates)
            }
            wantFree -> {
                cheapestCandidate(candidates, requireFree = true)
                    ?: cheapestCandidate(candidates)
            }
            wantUntethered -> {
                cheapestCandidate(candidates, requireUntethered = true)
                    ?: cheapestCandidate(candidates)
            }
            wantSignal -> {
                cheapestCandidate(candidates, requireSignal = true)
                    ?: cheapestCandidate(candidates)
            }
            else -> cheapestCandidate(candidates)
        }

        val alternatives = ArrayList<BypassFeature>()
        val freeOptions = ArrayList<BypassFeature>()
        val signalOptions = ArrayList<BypassFeature>()
        for (candidate in candidates) {
            if (candidate.id != best?.id) {
                alternatives.add(candidate)
            }
            if (candidate.isFree) {
                freeOptions.add(candidate)
            }
            if (candidate.signalAfter) {
                signalOptions.add(candidate)
            }
        }
        alternatives.sortBy { it.costCredits }

        val reasoning = buildString {
            append("Chip: ${device.chipName}. ")
            if (wantSignal)     append("Signal requested. ")
            if (wantFree)       append("Free preferred. ")
            if (wantUntethered) append("Untethered preferred. ")
            best?.let {
                append("Best: ${it.displayName}")
                if (it.isFree) append(" (FREE)") else append(" (${it.costCredits} credits)")
            } ?: append("No match found.")
        }

        return RecommendationResult(
            best          = best,
            alternatives  = alternatives.take(4),
            freeOptions   = candidates.filter { it.isFree },
            signalOptions = signalOptions,
            reasoning     = reasoning,
            device        = device,
        )
    }

    // ── Execution plan ────────────────────────────────────────────────────────

    fun buildPlan(feature: BypassFeature, device: DeviceState, sessionId: String): ExecutionPlan {
        val prereqs = ArrayList<Prerequisite>()
        if (feature.requiresDfu) {
            prereqs.add(
                Prerequisite(
                    "DFU Mode Required",
                    device.dfuMode,
                    "Enter DFU: Side+VolDown 10s, release Side, hold VolDown 5s",
                )
            )
        }
        if (feature.requiresImei) {
            prereqs.add(
                Prerequisite(
                    "Valid IMEI",
                    device.imeiPresent && device.imeiValid,
                    "Device needs valid unblacklisted IMEI for signal features",
                )
            )
        }
        if (feature.requiresInternet) {
            prereqs.add(
                Prerequisite(
                    "Internet Connection",
                    true,
                    "Connect to WiFi or mobile data before proceeding",
                )
            )
        }
        if (feature.requiresJailbreak) {
            prereqs.add(
                Prerequisite(
                    "Active Jailbreak",
                    device.isJailbroken,
                    "Run Auto Jailbreak (iRa1n) first",
                )
            )
        }
        if (feature.connectionMode == "ADB") {
            prereqs.add(
                Prerequisite(
                    "ADB / USB Debugging",
                    device.adbAvailable,
                    "Enable Developer Options → USB Debugging on device",
                )
            )
        }
        if (feature.connectionMode == "EDL") {
            prereqs.add(
                Prerequisite(
                    "EDL Mode",
                    device.edlAvailable,
                    "Enter EDL: Vol+USB or adb reboot edl",
                )
            )
        }

        val blockers = ArrayList<String>()
        for (prerequisite in prereqs) {
            if (!prerequisite.met) {
                blockers.add(prerequisite.fixHint)
            }
        }

        val warnings = ArrayList<String>()
        if (feature.dataLoss) {
            warnings.add("⚠ DATA LOSS — all user data will be permanently erased")
        }
        if (feature.riskLevel == RiskLevel.EXTREME) {
            warnings.add("⚠ EXTREME RISK — irreversible operation")
        }
        if (!feature.isUntethered) {
            warnings.add("ℹ Tethered — bypass resets after full power cycle")
        }
        if (feature.requiresJailbreak && !device.isJailbroken) {
            warnings.add("Run Auto Jailbreak first")
        }

        return ExecutionPlan(
            feature = feature, device = device,
            prerequisites = prereqs, canExecute = blockers.isEmpty(),
            blockers = blockers, warnings = warnings, sessionId = sessionId,
        )
    }
