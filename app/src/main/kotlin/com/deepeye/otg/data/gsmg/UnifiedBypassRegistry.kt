    // ── Query API ─────────────────────────────────────────────────────────────

    fun find(id: String): BypassFeature? = byIdMap[id]

    fun byCategory(cat: FeatureCategory): List<BypassFeature> =
        byCategoryMap[cat] ?: emptyList()

    fun bySource(src: FeatureSource): List<BypassFeature> =
        bySourceMap[src] ?: emptyList()

    fun forChip(chip: ChipRange): List<BypassFeature> = all.filter {
        it.chipRange == chip ||
        it.chipRange == ChipRange.A7_TO_A18 ||
        (chip == ChipRange.A8_TO_A11 && it.chipRange == ChipRange.A7_TO_A11)
    }

    fun free(): List<BypassFeature>         = all.filter { it.isFree }
    fun withSignal(): List<BypassFeature>   = all.filter { it.signalAfter }
    fun untethered(): List<BypassFeature>   = all.filter { it.untethered }
    fun noDataLoss(): List<BypassFeature>   = all.filter { !it.dataLoss }
    fun withIServices(): List<BypassFeature> = all.filter { it.iServicesAfter }
    fun noJailbreak(): List<BypassFeature>  = all.filter { !it.requiresJailbreak }
    fun offlineOnly(): List<BypassFeature>  = all.filter { !it.requiresInternet }

    fun search(q: String): List<BypassFeature> {
        if (q.isBlank()) return all
        val lower = q.lowercase().trim()
        return all.filter {
            lower in it.displayName.lowercase() ||
            lower in it.description.lowercase() ||
            it.tags.any { tag -> lower in tag }
        }
    }

    fun bypassOptions(chip: ChipRange): List<BypassFeature> =
        forChip(chip)
            .filter { it.category == FeatureCategory.ICLOUD_BYPASS }
            .sortedWith(compareBy({ it.costCredits }, { it.riskLevel.ordinal }))

    fun countByCategory(): Map<FeatureCategory, Int> =
        byCategoryMap.mapValues { it.value.size }

    fun countBySource(): Map<FeatureSource, Int> =
        bySourceMap.mapValues { it.value.size }

    // ── Recommendation engine ─────────────────────────────────────────────────

    fun recommend(
        device:        DeviceState,
        wantSignal:    Boolean = false,
        wantFree:      Boolean = false,
        wantUntethered:Boolean = false,
    ): RecommendationResult {
        val candidates = bypassOptions(device.chipRange)
            .filter { !it.requiresJailbreak || device.isJailbroken }
            .filter { !it.requiresImei    || device.canUseSignal }

        val best = when {
            wantSignal && wantFree ->
                candidates.firstOrNull { it.signalAfter && it.isFree }
                    ?: candidates.filter { it.signalAfter }.minByOrNull { it.costCredits }
                    ?: candidates.minByOrNull { it.costCredits }

            wantSignal && wantUntethered ->
                candidates.filter { it.signalAfter && it.untethered }
                    .minByOrNull { it.costCredits }
                    ?: candidates.filter { it.signalAfter }.minByOrNull { it.costCredits }

            wantFree ->
                candidates.firstOrNull { it.isFree }
                    ?: candidates.minByOrNull { it.costCredits }

            wantUntethered ->
                candidates.filter { it.untethered }.minByOrNull { it.costCredits }
                    ?: candidates.minByOrNull { it.costCredits }

            wantSignal ->
                candidates.filter { it.signalAfter }.minByOrNull { it.costCredits }
                    ?: candidates.minByOrNull { it.costCredits }

            else -> candidates.minByOrNull { it.costCredits }
        }

        val reasoning = buildString {
            append("Chip: ${device.chipName}. ")
            if (wantSignal)     append("Signal requested. ")
            if (wantFree)       append("Free preferred. ")
            if (wantUntethered) append("Untethered preferred. ")
            best?.let {
                append("Best: ${it.displayName}")
                if (it.isFree) append(" (FREE)")  
                else append(" (${it.costCredits} credits)")
            } ?: append("No match found for current preferences.")
        }

        return RecommendationResult(
            best          = best,
            alternatives  = candidates
                .filter { it.id != best?.id }
                .sortedBy { it.costCredits }
                .take(4),
            freeOptions   = candidates.filter { it.isFree },
            signalOptions = candidates.filter { it.signalAfter },
            reasoning     = reasoning,
            device        = device,
        )
    }

    // ── Execution plan ────────────────────────────────────────────────────────

    fun buildPlan(
        feature:   BypassFeature,
        device:    DeviceState,
        sessionId: String,
    ): ExecutionPlan {
        val prereqs = buildList {
            if (feature.requiresDfu)
                add(Prerequisite(
                    name    = "DFU Mode Required",
                    met     = device.dfuMode,
                    fixHint = "Enter DFU: Side+VolDown 10s, release Side, hold VolDown 5s",
                ))
            if (feature.requiresImei)
                add(Prerequisite(
                    name    = "Valid IMEI",
                    met     = device.imeiPresent && device.imeiValid,
                    fixHint = "Device must have a valid, unblacklisted IMEI for signal features",
                ))
            if (feature.requiresInternet)
                add(Prerequisite(
                    name    = "Internet Connection",
                    met     = true, // assumed — verified at runtime
                    fixHint = "Connect to WiFi or mobile data before proceeding",
                ))
            if (feature.requiresJailbreak)
                add(Prerequisite(
                    name    = "Active Jailbreak",
                    met     = device.isJailbroken,
                    fixHint = "Run Auto Jailbreak (iRa1n) first, then retry",
                ))
        }

        val blockers = prereqs.filter { !it.met }.map { it.fixHint }

        val warnings = buildList {
            if (feature.dataLoss)
                add("⚠ DATA LOSS — all user data will be permanently and irreversibly erased")
            if (feature.riskLevel == RiskLevel.EXTREME)
                add("⚠ EXTREME RISK — this operation cannot be undone")
            if (!feature.untethered)
                add("ℹ Tethered — bypass resets after full power cycle, re-run to restore")
            if (feature.requiresJailbreak && !device.isJailbroken)
                add("Run Auto Jailbreak (iRa1n) before executing this operation")
        }

        return ExecutionPlan(
            feature       = feature,
            device        = device,
            prerequisites = prereqs,
            canExecute    = blockers.isEmpty(),
            blockers      = blockers,
            warnings      = warnings,
            sessionId     = sessionId,
        )
    }
