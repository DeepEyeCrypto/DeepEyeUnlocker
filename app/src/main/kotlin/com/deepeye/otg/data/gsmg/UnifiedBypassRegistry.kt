    private fun buildCategoryCounts(features: List<BypassFeature>): Map<FeatureCategory, Int> {
        val counts = LinkedHashMap<FeatureCategory, Int>()
        for (feature in features) {
            counts[feature.category] = (counts[feature.category] ?: 0) + 1
        }
        return counts
    }

    private fun buildSourceCounts(features: List<BypassFeature>): Map<FeatureSource, Int> {
        val counts = LinkedHashMap<FeatureSource, Int>()
        for (feature in features) {
            counts[feature.source] = (counts[feature.source] ?: 0) + 1
        }
        return counts
    }

    private fun cheapestCandidate(
        features: List<BypassFeature>,
        requireSignal: Boolean? = null,
        requireFree: Boolean? = null,
        requireUntethered: Boolean? = null,
    ): BypassFeature? {
        var cheapest: BypassFeature? = null
        for (feature in features) {
            if (requireSignal != null && feature.signalAfter != requireSignal) continue
            if (requireFree != null && feature.isFree != requireFree) continue
            if (requireUntethered != null && feature.isUntethered != requireUntethered) continue
            if (cheapest == null || feature.costCredits < cheapest.costCredits) {
                cheapest = feature
            }
        }
        return cheapest
    }

