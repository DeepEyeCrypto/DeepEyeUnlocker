    fun forChip(chip: ChipRange): List<BypassFeature> = all.filter {
        it.chipRange == chip || it.chipRange == ChipRange.ALL_ANDROID ||
        it.chipRange == ChipRange.ALL_DEVICES ||
        (chip == ChipRange.MTK_V6 && it.chipRange == ChipRange.MTK_ALL) ||
        (chip == ChipRange.MTK_CLASSIC && it.chipRange == ChipRange.MTK_ALL) ||
        (chip == ChipRange.SAMSUNG_EXYNOS && it.chipRange == ChipRange.SAMSUNG_ALL) ||
        (chip == ChipRange.SAMSUNG_QC && it.chipRange == ChipRange.SAMSUNG_ALL) ||
        (chip == ChipRange.A8_TO_A11 && it.chipRange == ChipRange.A7_TO_A11)
    }

