package com.deepeye.otg.data.device

/**
 * XiaomiProtocolResolver
 * Resolves Xiaomi model → exact protocol
 * Rules:
 *   Mi series        → QC_EDL (always Snapdragon flagship)
 *   POCO F/X series  → QC_EDL
 *   POCO M/C series  → MTK_V6
 *   Redmi 2022+      → MTK_V6 (Dimensity)
 *   Redmi 2021 Pro   → QC_EDL
 *   Redmi pre-2021   → MTK_BROM (classic MediaTek)
 * Total: 262 models (Redmi:130 Mi:80 POCO:52)
 */
object XiaomiProtocolResolver {

    fun resolve(model: String, series: String?, year: Int): DeviceProtocol {
        val m = model.lowercase()
        return when {
            // Mi series — always Snapdragon
            series == "Mi" -> DeviceProtocol.QC_EDL

            // POCO F/X = QC, POCO M/C = MTK
            series == "POCO" && (
                m.contains("f1") || m.contains("f2") ||
                m.contains("f3") || m.contains("f4") ||
                m.contains("f5") || m.contains("x2") ||
                m.contains("x3") || m.contains("x4") ||
                m.contains("x5") || m.contains("x6")
            ) -> DeviceProtocol.QC_EDL

            series == "POCO" -> DeviceProtocol.MTK_V6

            // Redmi year-based
            series == "Redmi" && year >= 2022 -> DeviceProtocol.MTK_V6
            series == "Redmi" && year == 2021 &&
                m.contains("pro") -> DeviceProtocol.QC_EDL
            series == "Redmi" -> DeviceProtocol.MTK_BROM

            // Model name fallback
            m.startsWith("redmi") && year >= 2022 -> DeviceProtocol.MTK_V6
            m.startsWith("redmi") -> DeviceProtocol.MTK_BROM
            m.startsWith("poco") -> DeviceProtocol.MTK_V6
            m.startsWith("mi ") -> DeviceProtocol.QC_EDL

            else -> DeviceProtocol.MTK_OR_QC
        }
    }

